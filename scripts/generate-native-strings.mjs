#!/usr/bin/env node
// Generates the Swift string tables the Watch app and the iOS widget render from.
//
// The targets are built as Xcode file-system-synchronized folders and nothing sets
// knownRegions, so .lproj and .xcstrings resources can fail to reach the built
// bundle while the build still succeeds. A generated Swift table is compiled like
// any other source in the folder, so it cannot go missing. It also matches the real
// requirement: these surfaces must render the language chosen in the app, not the
// device locale, which needs an explicit lookup either way.
//
//   node scripts/generate-native-strings.mjs           # write the tables
//   node scripts/generate-native-strings.mjs --check    # fail if they are stale
//
// Exit codes: 0 written or up to date, 1 stale under --check, 2 the tool failed.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const STRINGS_DIR = resolve(here, "..", "localization", "native");
const TARGETS = [
  resolve(here, "..", "targets", "watch"),
  resolve(here, "..", "targets", "widget"),
];

export const SHIPPED_LOCALES = [
  "en",
  "sr",
  "es",
  "es-ES",
  "fr",
  "pt-PT",
  "pt-BR",
  "de",
  "it",
];

const APP_GROUP = "group.com.sofibaby.app";
const STORAGE_KEY = "appLanguage";
const EXIT_STALE = 1;
const EXIT_TOOL_FAILURE = 2;

function fail(message) {
  console.error(message);
  process.exit(EXIT_TOOL_FAILURE);
}

export function swiftLiteral(value) {
  return `"${value
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
    .replace(/\t/g, "\\t")}"`;
}

function loadLocales() {
  const tables = new Map();
  for (const locale of SHIPPED_LOCALES) {
    const path = join(STRINGS_DIR, `${locale}.json`);
    let parsed;
    try {
      parsed = JSON.parse(readFileSync(path, "utf8"));
    } catch (error) {
      fail(`${locale}.json: ${error.message}`);
    }
    if (parsed === null || typeof parsed !== "object" || Array.isArray(parsed)) {
      fail(`${locale}.json: expected a JSON object at the root`);
    }
    tables.set(locale, parsed);
  }
  return tables;
}

export function isPluralForm(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

const PLURAL_CATEGORIES = ["one", "few", "many", "other"];

export function renderSwift(tables, keys) {
  const lines = [];
  lines.push("// Generated by scripts/generate-native-strings.mjs — do not edit by hand.");
  lines.push("// Source of truth: localization/native/*.json");
  lines.push("");
  lines.push("import Foundation");
  lines.push("");
  lines.push("/// The language the caregiver selected in the phone app.");
  lines.push("///");
  lines.push("/// The phone publishes the resolved, region-preserving code; it never publishes");
  lines.push("/// the stored \"system\" preference. Before the phone has ever published one, the");
  lines.push("/// device locale is mapped with the same rules the app uses, so this surface");
  lines.push("/// agrees with what the phone itself would show rather than defaulting to English.");
  lines.push("enum NativeLanguageResolver {");
  lines.push(`    static let appGroup = ${swiftLiteral(APP_GROUP)}`);
  lines.push(`    static let storageKey = ${swiftLiteral(STORAGE_KEY)}`);
  lines.push("");
  lines.push("    static var current: String {");
  lines.push("        if let stored = UserDefaults(suiteName: appGroup)?.string(forKey: storageKey),");
  lines.push("           L.supportedLanguages.contains(stored) {");
  lines.push("            return stored");
  lines.push("        }");
  lines.push("        return deviceLanguage()");
  lines.push("    }");
  lines.push("");
  lines.push("    static func deviceLanguage(");
  lines.push("        locale: Locale = .current");
  lines.push("    ) -> String {");
  lines.push("        let language = locale.language.languageCode?.identifier ?? \"en\"");
  lines.push("        let region = locale.region?.identifier");
  lines.push("        return resolve(language: language, region: region)");
  lines.push("    }");
  lines.push("");
  lines.push("    /// Mirrors getDeviceLanguage() in src/contexts/language-context.tsx.");
  lines.push("    static func resolve(language: String, region: String?) -> String {");
  lines.push("        switch language {");
  lines.push("        case \"sr\": return \"sr\"");
  lines.push("        case \"es\": return region == \"ES\" ? \"es-ES\" : \"es\"");
  lines.push("        case \"fr\": return \"fr\"");
  lines.push("        case \"pt\": return region == \"BR\" ? \"pt-BR\" : \"pt-PT\"");
  lines.push("        case \"de\": return \"de\"");
  lines.push("        case \"it\": return \"it\"");
  lines.push("        default: return \"en\"");
  lines.push("        }");
  lines.push("    }");
  lines.push("}");
  lines.push("");
  lines.push("enum L {");
  lines.push(
    `    static let supportedLanguages: [String] = [${SHIPPED_LOCALES.map(swiftLiteral).join(", ")}]`
  );
  lines.push("");
  lines.push("    static var language: String { NativeLanguageResolver.current }");
  lines.push("");
  lines.push("    static func t(_ key: String) -> String {");
  lines.push("        if let value = table[language]?[key] { return value }");
  lines.push("        if let english = table[\"en\"]?[key] { return english }");
  lines.push("        return key");
  lines.push("    }");
  lines.push("");
  lines.push("    /// CLDR cardinal category. Serbian inflects 2-4 separately from 5+,");
  lines.push("    /// and French and Portuguese treat 0 as singular.");
  lines.push("    static func pluralCategory(language: String, count: Int) -> String {");
  lines.push("        let n = abs(count)");
  lines.push("        switch language {");
  lines.push("        case \"sr\":");
  lines.push("            let mod10 = n % 10");
  lines.push("            let mod100 = n % 100");
  lines.push("            if mod10 == 1 && mod100 != 11 { return \"one\" }");
  lines.push("            if (2...4).contains(mod10) && !(12...14).contains(mod100) { return \"few\" }");
  lines.push("            return \"other\"");
  lines.push("        case \"fr\", \"pt-PT\", \"pt-BR\":");
  lines.push("            return n <= 1 ? \"one\" : \"other\"");
  lines.push("        default:");
  lines.push("            return n == 1 ? \"one\" : \"other\"");
  lines.push("        }");
  lines.push("    }");
  lines.push("");
  lines.push("    static func p(_ key: String, _ count: Int) -> String {");
  lines.push("        let forms = pluralTable[language]?[key] ?? pluralTable[\"en\"]?[key]");
  lines.push("        let category = pluralCategory(language: language, count: count)");
  lines.push("        guard let form = forms?[category] ?? forms?[\"other\"] ?? forms?[\"one\"] else {");
  lines.push("            return key");
  lines.push("        }");
  lines.push("        return String(format: form, count)");
  lines.push("    }");
  lines.push("");

  const english = tables.get("en");
  const flatKeys = keys.filter((key) => !isPluralForm(english[key]));
  const pluralKeys = keys.filter((key) => isPluralForm(english[key]));

  for (const key of flatKeys) {
    lines.push(`    static var ${key}: String { t(${swiftLiteral(key)}) }`);
  }
  for (const key of pluralKeys) {
    lines.push(`    static func ${key}(_ count: Int) -> String { p(${swiftLiteral(key)}, count) }`);
  }

  lines.push("");
  lines.push("    private static let table: [String: [String: String]] = [");
  for (const locale of SHIPPED_LOCALES) {
    const entries = tables.get(locale);
    const rows = flatKeys
      .filter((key) => typeof entries[key] === "string")
      .map((key) => `            ${swiftLiteral(key)}: ${swiftLiteral(entries[key])},`);
    if (rows.length === 0) {
      lines.push(`        ${swiftLiteral(locale)}: [:],`);
      continue;
    }
    lines.push(`        ${swiftLiteral(locale)}: [`);
    lines.push(...rows);
    lines.push("        ],");
  }
  lines.push("    ]");
  lines.push("");
  lines.push("    private static let pluralTable: [String: [String: [String: String]]] = [");
  for (const locale of SHIPPED_LOCALES) {
    const entries = tables.get(locale);
    const rows = pluralKeys
      .filter((key) => isPluralForm(entries[key]))
      .map((key) => {
        const forms = entries[key];
        const rendered = PLURAL_CATEGORIES.filter((category) => typeof forms[category] === "string")
          .map((category) => `${swiftLiteral(category)}: ${swiftLiteral(forms[category])}`)
          .join(", ");
        return `            ${swiftLiteral(key)}: [${rendered}],`;
      });
    if (rows.length === 0) {
      lines.push(`        ${swiftLiteral(locale)}: [:],`);
      continue;
    }
    lines.push(`        ${swiftLiteral(locale)}: [`);
    lines.push(...rows);
    lines.push("        ],");
  }
  lines.push("    ]");
  lines.push("}");
  lines.push("");
  return lines.join("\n");
}

const checkOnly = process.argv.includes("--check");
const tables = loadLocales();
const keys = Object.keys(tables.get("en")).sort();

if (keys.length === 0) fail("localization/native/en.json declares no keys");

const rendered = renderSwift(tables, keys);
let stale = 0;

for (const target of TARGETS) {
  const path = join(target, "GeneratedStrings.swift");
  let existing = null;
  try {
    existing = readFileSync(path, "utf8");
  } catch {
    existing = null;
  }

  if (existing === rendered) continue;

  if (checkOnly) {
    console.error(`${path} is out of date; run: node scripts/generate-native-strings.mjs`);
    stale += 1;
    continue;
  }

  mkdirSync(target, { recursive: true });
  writeFileSync(path, rendered);
  console.log(`wrote ${path} (${keys.length} keys × ${SHIPPED_LOCALES.length} locales)`);
}

if (stale) process.exit(EXIT_STALE);
if (checkOnly) console.log(`Generated string tables are up to date (${keys.length} keys).`);
